"""Collect evaluated checkpoints into one tracked record: a markdown gate table and a JSON of the gate rows.

The raw evaluations (runs/*_eval*.json, ~0.6 MB each) and the sensitivity matrices (runs/sens/) are
gitignored. This keeps what a decision was made on in the repo: one row per checkpoint with the
gated metrics, judged against the v1 baseline as `eval_walk.py --compare` does, plus each
sensitivity matrix's table.md.

usage:
  uv run scripts/gate_summary.py                  # -> docs/results/hd1910_gates.{md,json}, docs/results/sens_<tag>.md
"""
import json
import re
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNS = REPO / "runs"
OUT = REPO / "docs" / "results"
BASELINE = RUNS / "hd1910_v1_final_eval_h2.json"
COLUMNS = [  # (short header, gate row name)
    ("fwd .10", "fwd 0.10 vx [m/s]"), ("fwd .20", "fwd 0.20 vx [m/s]"), ("fwd .30", "fwd 0.30 vx [m/s]"),
    ("back .10", "back 0.10 vx [m/s]"), ("left .10", "left 0.10 vy [m/s]"),
    ("turn mean/min", ("turn |wz| mean [rad/s]", "turn |wz| min [rad/s]")),
    ("turn rest @1/@.5", ("turn from rest |wz| min @1.0 [rad/s]", "turn from rest |wz| min @0.5 [rad/s]")),
    ("stand max/legs", ("stand torque max joint [N.m]", "stand torque leg sum [N.m]")),
    ("peak", "substep peak worst [N.m]"), ("falls/0.4", ("falls (sched/steps/stand/kick<=0.3)", "falls at the 0.4 kick (report)")),
]


def _load(name):
    import importlib.util
    spec = importlib.util.spec_from_file_location(name, REPO / "scripts" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def label(path: Path) -> tuple[str, int]:
    """'v2d_s42@5999 (h3)' and a sort key from an eval file name."""
    stem = path.stem.replace("hd1910_", "").replace("_eval", "")
    harness = "h3" if stem.endswith("_h3") else ("h2" if stem.endswith("_h2") else "h2")
    stem = re.sub(r"_h[23]$", "", stem)
    m = re.match(r"(.*?)_(\d+|final)$", stem)
    run, it = (m.group(1), m.group(2)) if m else (stem, "")
    num = 10**6 if it == "final" else int(it or 0)
    return f"{run}@{it} ({harness})", num


def main():
    ev = _load("eval_walk")
    base = json.loads(BASELINE.read_text())
    files = sorted(p for p in RUNS.glob("*eval*.json") if p.name != BASELINE.name)
    # Prefer the harness-v3 file when a checkpoint was evaluated under both.
    chosen = {}
    for p in files:
        lab, num = label(p)
        key = lab.split(" (")[0]
        if key not in chosen or "(h3)" in lab:
            chosen[key] = (p, lab, num)
    records, lines = [], []
    head = ["checkpoint", *[c for c, _ in COLUMNS], "failing gate rows"]
    lines += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    fmt = lambda v: "n/a" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))
    for key, (p, lab, num) in sorted(chosen.items(), key=lambda kv: (kv[0].split("@")[0], kv[1][2])):
        doc = json.loads(p.read_text())
        reps = (doc.get("args") or {}).get("replicas", 1)
        lab = lab.replace(")", f", {reps}r)")
        rows = ev.gate_rows(base, doc)
        by = {n: (y, v) for n, _, y, v in rows}
        cells = []
        for _, col in COLUMNS:
            names = col if isinstance(col, tuple) else (col,)
            cells.append(" / ".join(fmt(by[n][0]) + (" ✗" if by[n][1] == "FAIL" else "") for n in names))
        failing = [n.split(" [")[0] for n, (_, v) in by.items() if v == "FAIL"]
        lines.append(f"| {lab} | " + " | ".join(cells) + f" | {', '.join(failing) or '-'} |")
        records.append(dict(checkpoint=lab, source=p.name, replicas=reps, rows={n: {"value": y, "verdict": v} for n, (y, v) in by.items()}))
    OUT.mkdir(parents=True, exist_ok=True)
    intro = (f"# HD-1910 gate table, every evaluated checkpoint\n\nGenerated by `scripts/gate_summary.py` from the "
             f"gitignored `runs/*eval*.json`; judged against `{BASELINE.name}` like `eval_walk.py --compare` "
             f"(✗ = gated row fails). h2 = harness v2 (no turn-from-rest rollout: those cells read n/a), "
             f"h3 = harness v3; `3r` = replicas averaged.\n\n")
    (OUT / "hd1910_gates.md").write_text(intro + "\n".join(lines) + "\n")
    (OUT / "hd1910_gates.json").write_text(json.dumps(records, indent=1))
    for d in sorted((RUNS / "sens").glob("*/table.md")):
        shutil.copy(d, OUT / f"sens_{d.parent.name}.md")
    print(f"{len(records)} checkpoints -> {OUT / 'hd1910_gates.md'}; {len(list((RUNS / 'sens').glob('*/table.md')))} matrices")


if __name__ == "__main__":
    main()
